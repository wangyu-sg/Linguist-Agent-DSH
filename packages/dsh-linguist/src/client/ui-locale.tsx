const LocaleContext = React.createContext<LocaleRuntime>(null!)

export function registerLinguistLocale(locale: LocaleRuntime): () => void {
  const chinese = Object.fromEntries(Object.keys(english).map((key) => [key, key]))
  const disposeZh = locale.register('linguist', 'zh', chinese)
  const disposeEn = locale.register('linguist', 'en', english)
  return () => { disposeEn(); disposeZh() }
}

export function LocaleProvider({ locale, children }: { locale: LocaleRuntime; children?: React.ReactNode }): React.ReactElement {
  return <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>
}

export function useT(): (key: string, params?: Record<string, unknown>) => string {
  const locale = React.useContext(LocaleContext)
  React.useSyncExternalStore(locale.subscribe.bind(locale), locale.getSnapshot.bind(locale))
  return locale.bind('linguist')
}

export function useLocaleId(): string {
  const locale = React.useContext(LocaleContext)
  return React.useSyncExternalStore(locale.subscribe.bind(locale), locale.getSnapshot.bind(locale)).active
}
